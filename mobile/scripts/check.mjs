import assert from 'node:assert/strict';
import {readFile,access} from 'node:fs/promises';
const config=JSON.parse(await readFile(new URL('../capacitor.config.json',import.meta.url)));
assert.equal(config.appId,'io.github.troglobiont.valestudy');
assert.equal(config.webDir,'www');
assert.equal(config.server?.url,undefined,'Native app must load bundled files, not the website');
const html=await readFile(new URL('../www/index.html',import.meta.url),'utf8');
assert(html.indexOf('native.js')<html.indexOf('app.js'));
assert(!html.includes('rel="manifest"'));
await access(new URL('../www/avatar.js',import.meta.url));
for(const file of ['nature-data.js','nature-core.js','nature-ui.js','garden-core.js','garden-ui.js','math-test-core.js','math-test-ui.js','english-practice.js','english-practice-ui.js','english-data.js','english-core.js','english.js','updates.js'])await access(new URL('../www/'+file,import.meta.url));
const book=JSON.parse(await readFile(new URL('../www/book.json',import.meta.url)));
assert.equal(book.tasks.length,151);
assert.equal(config.plugins.CapacitorUpdater.autoUpdate,'off');
assert.equal(config.plugins.CapacitorUpdater.statsUrl,'');
const manifest=JSON.parse(await readFile(new URL('../../version.json',import.meta.url)));
assert.equal(manifest.minNativeVersion,'0.7.0');
console.log('Native offline bundle and updater checks passed');
